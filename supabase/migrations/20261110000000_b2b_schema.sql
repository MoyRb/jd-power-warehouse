-- ---------------------------------------------------------------------------
-- quotes
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS quotes (
  id            UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  quote_ref     TEXT        NOT NULL UNIQUE,  -- e.g. QT-2026-0001
  customer_id   UUID        REFERENCES business_customers(id) ON DELETE RESTRICT,
  -- Captured from anonymous submission (may be populated from customer later)
  anon_name     TEXT,
  anon_email    TEXT,
  anon_phone    TEXT,
  anon_company  TEXT,
  -- State
  status        TEXT        NOT NULL DEFAULT 'pending'
                              CHECK (status IN ('pending','reviewing','sent','accepted','rejected','expired')),
  currency_code TEXT        NOT NULL DEFAULT 'USD',
  admin_notes   TEXT,
  valid_until   DATE,
  ip_hash       TEXT,
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE OR REPLACE TRIGGER quotes_updated_at
  BEFORE UPDATE ON quotes
  FOR EACH ROW EXECUTE FUNCTION update_updated_at_column();

-- ---------------------------------------------------------------------------
-- quote_lines
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS quote_lines (
  id                 UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  quote_id           UUID        NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
  product_id         UUID        REFERENCES products(id) ON DELETE RESTRICT,  -- NULL = free-form line
  quantity           INT         NOT NULL CHECK (quantity > 0),
  description        TEXT,       -- required when product_id IS NULL; optional label for catalog lines
  unit_list_price    NUMERIC(10,2) CHECK (unit_list_price >= 0),  -- snapshot of catalog price at submission
  unit_quoted_price  NUMERIC(10,2) CHECK (unit_quoted_price >= 0),  -- set by admin
  currency_code      TEXT        NOT NULL DEFAULT 'USD',
  customer_note      TEXT,
  sort_order         INT         NOT NULL DEFAULT 0,
  created_at         TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  -- Business rule: every line must reference a catalog product OR have a description
  CONSTRAINT line_requires_product_or_description
    CHECK (product_id IS NOT NULL OR (description IS NOT NULL AND trim(description) <> ''))
);

-- ---------------------------------------------------------------------------
-- quote_events  (immutable ledger — no UPDATE or DELETE allowed)
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS quote_events (
  id          UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  quote_id    UUID        NOT NULL REFERENCES quotes(id) ON DELETE CASCADE,
  admin_id    UUID        REFERENCES auth.users(id) ON DELETE SET NULL,
  event_type  TEXT        NOT NULL
                CHECK (event_type IN ('status_change','note_added','price_set','line_added','line_removed','reopened')),
  old_status  TEXT,
  new_status  TEXT,
  note        TEXT,
  created_at  TIMESTAMPTZ NOT NULL DEFAULT NOW()
  -- No updated_at — this table is append-only
);

-- ---------------------------------------------------------------------------
-- State machine helper (IMMUTABLE — used in CHECK and RPC)
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION validate_quote_transition(
  from_status TEXT,
  to_status   TEXT
) RETURNS BOOLEAN AS $$
BEGIN
  RETURN CASE
    WHEN from_status = 'pending'   AND to_status IN ('reviewing', 'rejected')           THEN TRUE
    WHEN from_status = 'reviewing' AND to_status IN ('sent', 'rejected')                THEN TRUE
    WHEN from_status = 'sent'      AND to_status IN ('accepted', 'rejected', 'expired') THEN TRUE
    WHEN from_status = 'expired'   AND to_status = 'reviewing'                          THEN TRUE
    ELSE FALSE
  END;
END;
$$ LANGUAGE plpgsql IMMUTABLE SECURITY DEFINER SET search_path = public, pg_temp;

-- ---------------------------------------------------------------------------
-- Public RPC: create_quote_with_lines (called by anon — SECURITY DEFINER)
--
-- Security properties:
--   * Runs as the function owner (superuser / db owner), not as the anon caller.
--   * Validates all inputs before any INSERT.
--   * Snapshots product price from DB — never trusts client-supplied prices.
--   * Does NOT expose existing quotes or other rows to the caller.
--   * Returns only {id, quote_ref} — no internal data.
--   * search_path locked to prevent schema injection.
--   * GRANT EXECUTE to anon is in migration 20261110000001_b2b_rls.sql.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION create_quote_with_lines(
  p_anon_name    TEXT,
  p_anon_email   TEXT,
  p_anon_phone   TEXT,
  p_anon_company TEXT,
  p_lines        JSONB,
  p_ip_hash      TEXT
) RETURNS JSONB
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_quote_id   UUID;
  v_quote_ref  TEXT;
  v_line       JSONB;
  v_line_index INT := 0;
  v_product    RECORD;
  v_qty        INT;
  v_desc       TEXT;
  v_pid        UUID;
BEGIN
  -- ── Input validation ──────────────────────────────────────────────────────
  IF p_anon_name IS NULL OR length(trim(p_anon_name)) = 0 THEN
    RAISE EXCEPTION 'name_required';
  END IF;
  IF length(trim(p_anon_name)) > 100 THEN
    RAISE EXCEPTION 'name_too_long';
  END IF;
  IF p_anon_email IS NULL OR length(trim(p_anon_email)) = 0 THEN
    RAISE EXCEPTION 'email_required';
  END IF;
  IF p_anon_email NOT LIKE '%@%.%' THEN
    RAISE EXCEPTION 'email_invalid';
  END IF;
  IF p_lines IS NULL OR jsonb_typeof(p_lines) <> 'array' OR jsonb_array_length(p_lines) = 0 THEN
    RAISE EXCEPTION 'lines_required';
  END IF;
  IF jsonb_array_length(p_lines) > 20 THEN
    RAISE EXCEPTION 'too_many_lines';
  END IF;

  -- ── Generate quote reference ───────────────────────────────────────────
  v_quote_ref := 'QT-' || TO_CHAR(NOW() AT TIME ZONE 'UTC', 'YYYY') || '-'
                 || LPAD(nextval('quote_ref_seq')::TEXT, 4, '0');

  -- ── Insert quote header ────────────────────────────────────────────────
  INSERT INTO quotes (quote_ref, anon_name, anon_email, anon_phone, anon_company, ip_hash)
  VALUES (
    v_quote_ref,
    trim(p_anon_name),
    lower(trim(p_anon_email)),
    NULLIF(trim(COALESCE(p_anon_phone, '')), ''),
    NULLIF(trim(COALESCE(p_anon_company, '')), ''),
    p_ip_hash
  )
  RETURNING id INTO v_quote_id;

  -- ── Insert lines ───────────────────────────────────────────────────────
  FOR v_line IN SELECT value FROM jsonb_array_elements(p_lines)
  LOOP
    v_line_index := v_line_index + 1;

    -- Validate quantity
    BEGIN
      v_qty := (v_line->>'quantity')::INT;
    EXCEPTION WHEN others THEN
      RAISE EXCEPTION 'line_%_invalid_quantity', v_line_index;
    END;
    IF v_qty IS NULL OR v_qty <= 0 THEN
      RAISE EXCEPTION 'line_%_quantity_must_be_positive', v_line_index;
    END IF;
    IF v_qty > 99999 THEN
      RAISE EXCEPTION 'line_%_quantity_too_large', v_line_index;
    END IF;

    v_desc := NULLIF(trim(COALESCE(v_line->>'description', '')), '');
    v_pid  := NULL;

    IF (v_line->>'product_id') IS NOT NULL AND (v_line->>'product_id') <> '' THEN
      -- Catalog line: validate product exists and is published
      BEGIN
        v_pid := (v_line->>'product_id')::UUID;
      EXCEPTION WHEN others THEN
        RAISE EXCEPTION 'line_%_invalid_product_id', v_line_index;
      END;

      SELECT id, price INTO v_product
      FROM products
      WHERE id = v_pid AND status = 'published';

      IF NOT FOUND THEN
        RAISE EXCEPTION 'line_%_product_not_found', v_line_index;
      END IF;

      INSERT INTO quote_lines (
        quote_id, product_id, quantity, description,
        unit_list_price, sort_order
      ) VALUES (
        v_quote_id, v_pid, v_qty, v_desc,
        v_product.price, v_line_index
      );

    ELSE
      -- Free-form line: description required
      IF v_desc IS NULL THEN
        RAISE EXCEPTION 'line_%_requires_product_or_description', v_line_index;
      END IF;
      IF length(v_desc) > 500 THEN
        RAISE EXCEPTION 'line_%_description_too_long', v_line_index;
      END IF;

      INSERT INTO quote_lines (
        quote_id, product_id, quantity, description,
        unit_list_price, sort_order
      ) VALUES (
        v_quote_id, NULL, v_qty, v_desc,
        NULL, v_line_index
      );
    END IF;
  END LOOP;

  RETURN jsonb_build_object('id', v_quote_id::TEXT, 'quote_ref', v_quote_ref);
END;
$$;

-- ---------------------------------------------------------------------------
-- Admin RPC: admin_update_quote_status (called by authenticated admin)
--
-- Security properties:
--   * Verifies is_admin() before any mutation.
--   * Enforces state machine via validate_quote_transition().
--   * Requires a note when reopening an expired quote.
--   * Writes quote_events atomically with the status update.
--   * GRANT EXECUTE to authenticated in migration 20261110000001_b2b_rls.sql.
-- ---------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION admin_update_quote_status(
  p_quote_id  UUID,
  p_new_status TEXT,
  p_admin_id  UUID,
  p_note      TEXT DEFAULT NULL
) RETURNS VOID
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $$
DECLARE
  v_old_status TEXT;
  v_event_type TEXT;
BEGIN
  IF NOT is_admin() THEN
    RAISE EXCEPTION 'unauthorized';
  END IF;

  SELECT status INTO v_old_status FROM quotes WHERE id = p_quote_id FOR UPDATE;
  IF NOT FOUND THEN
    RAISE EXCEPTION 'quote_not_found';
  END IF;

  IF NOT validate_quote_transition(v_old_status, p_new_status) THEN
    RAISE EXCEPTION 'invalid_transition: % -> %', v_old_status, p_new_status;
  END IF;

  -- Reopen (expired → reviewing) requires a non-empty note per D4
  IF v_old_status = 'expired' AND p_new_status = 'reviewing' THEN
    IF p_note IS NULL OR trim(p_note) = '' THEN
      RAISE EXCEPTION 'reopen_requires_note';
    END IF;
    v_event_type := 'reopened';
  ELSE
    v_event_type := 'status_change';
  END IF;

  UPDATE quotes SET status = p_new_status WHERE id = p_quote_id;

  INSERT INTO quote_events (quote_id, admin_id, event_type, old_status, new_status, note)
  VALUES (p_quote_id, p_admin_id, v_event_type, v_old_status, p_new_status, p_note);
END;
$$;
