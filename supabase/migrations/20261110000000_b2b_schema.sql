-- ---------------------------------------------------------------------------
-- Sequence for human-readable quote references: QT-YYYY-NNNN
-- ---------------------------------------------------------------------------
CREATE SEQUENCE IF NOT EXISTS quote_ref_seq START 1 INCREMENT 1;

-- ---------------------------------------------------------------------------
-- business_customers
-- ---------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS business_customers (
  id            UUID        PRIMARY KEY DEFAULT gen_random_uuid(),
  company_name  TEXT        NOT NULL,
  contact_name  TEXT        NOT NULL,
  email         TEXT        NOT NULL,
  phone         TEXT,
  address       TEXT,
  country       TEXT,                       -- ISO-3166-1 alpha-2 (e.g. 'US', 'MX')
  tax_id        TEXT,                       -- optional; RFC / EIN / VAT / etc.
  tax_id_type   TEXT,                       -- 'RFC' | 'EIN' | 'VAT' | custom
  price_tier    TEXT,                       -- stub for future volume pricing (D3)
  notes         TEXT,                       -- internal admin notes
  created_at    TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at    TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

